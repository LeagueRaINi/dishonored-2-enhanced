"""Compiles shaders/*.hlsl (shared declarations in shaders/*.hlsli) to DXBC with the system d3dcompiler_47.dll and writes src/shaders_generated.h.

Run at build time so the mod never compiles shaders while the game runs.
"""
import ctypes
import pathlib
import sys
from ctypes import wintypes

root = pathlib.Path(sys.argv[1])
compiler = ctypes.WinDLL("d3dcompiler_47.dll")

D3DCompile = compiler.D3DCompile
D3DCompile.restype = ctypes.c_long
D3DCompile.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                       ctypes.c_char_p, ctypes.c_char_p, wintypes.UINT, wintypes.UINT,
                       ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]

D3DCOMPILE_OPTIMIZATION_LEVEL3 = 1 << 15


def blob_bytes(blob):
    vtbl = ctypes.cast(ctypes.cast(blob, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
    get_ptr = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vtbl[3])
    get_size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vtbl[4])
    release = ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(vtbl[2])
    data = ctypes.string_at(get_ptr(blob), get_size(blob))
    release(blob)
    return data


out = ["// Generated by tools/compile_shaders.py - do not edit.", "#pragma once", "#include <cstdint>", ""]
for path in sorted((root / "shaders").glob("*.hlsl")):
    src = path.read_bytes()
    code = ctypes.c_void_p()
    errors = ctypes.c_void_p()
    # Stage from the file name suffix: *_vs.hlsl / *_ps.hlsl, everything else is a compute shader.
    target = b"vs_5_0" if path.stem.endswith("_vs") else b"ps_5_0" if path.stem.endswith("_ps") else b"cs_5_0"
    # D3D_COMPILE_STANDARD_FILE_INCLUDE ((ID3DInclude*)1): #include resolves relative to the shader (shared .hlsli).
    hr = D3DCompile(src, len(src), str(path).encode(), None, ctypes.c_void_p(1), b"main", target,
                    D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, ctypes.byref(code), ctypes.byref(errors))
    if errors.value:
        print(blob_bytes(errors).decode(errors="replace"))
    if hr < 0:
        sys.exit(f"failed to compile {path.name}: 0x{hr & 0xffffffff:08x}")
    data = blob_bytes(code)
    stage = target[:2].decode()
    stem = path.stem[:-3] if stage in ("vs", "ps") else path.stem
    name = f"g_{stage}_{stem}"
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out.append(f"static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};")
    out.append("")
    print(f"{path.name}: {len(data)} bytes")

(root / "src" / "shaders_generated.h").write_text("\n".join(out))
